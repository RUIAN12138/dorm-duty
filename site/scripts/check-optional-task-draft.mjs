import assert from 'node:assert/strict';
import { createHarness } from './check-cloud-backend.mjs';
import { validateDormConfiguration } from '../shared/dorm-configuration.mjs';
const h = await createHarness();
const pages = [{id:'duty',label:'值日'},{id:'water',label:'抬水'},{id:'calendar',label:'日历'}];
const base = {name:'地板',content:'扫地',enabled:true,page:'duty',rotation:'round',display:'title',deadline:'22:00',interval:3};
const key = `task_${'a'.repeat(32)}`;
const config = {schema_version:2,policy:'soft',pages,tasks:[{...base,key:'floor'},{...base,key,name:'',content:'',enabled:false,page:'water'}]};
const create = async (name, configuration) => h.request('/guest/create',{method:'POST',data:{name,nickname:'创建者',members:[],...(configuration ? {configuration} : {})}});
try {
  const oldResponse = await create('旧宿舍'); assert.equal(oldResponse.status,201);
  const old = await oldResponse.json();
  const oldBoardResponse = await h.request(`/chores/board?invite_code=${old.invite_code}&member_id=${old.member_id}`,{token:old.access_token});
  assert.equal(oldBoardResponse.status,200);
  const snapshot = () => Object.fromEntries(['dormitories','chore_settings','chore_categories','chore_tasks','chore_reminders'].map(table => [table,h.db.sqlite.prepare(`SELECT * FROM ${table} WHERE ${table === 'dormitories' ? 'id' : 'dorm_id'}=? ORDER BY rowid`).all(old.dorm.id)]));
  const oldBefore = JSON.stringify(snapshot());
  assert.equal(validateDormConfiguration(config).tasks[1].name,'');
  const response = await create('新版宿舍',config); assert.equal(response.status,201,await response.clone().text());
  const room = await response.json();
  const stored = JSON.parse(h.db.sqlite.prepare('SELECT configuration FROM dorm_configurations WHERE dorm_id=?').get(room.dorm.id).configuration);
  assert.equal(stored.tasks[1].key,key); assert.equal(stored.tasks[1].enabled,false); assert.equal(stored.tasks[1].name,'');
  const boardResponse = await h.request(`/chores/board?invite_code=${room.invite_code}&member_id=${room.member_id}`,{token:room.access_token});
  assert.equal(boardResponse.status,200,await boardResponse.clone().text());
  const board=await boardResponse.json();
  assert.equal(board.categories.find(item=>item.key===key).enabled,false);
  assert.equal(board.today_tasks.some(item=>item.key===key),false);
  const invalid = {...config,tasks:[config.tasks[0],{...config.tasks[1],enabled:true}]};
  assert.throws(()=>validateDormConfiguration(invalid));
  const rejectedSave=await h.request('/chores/settings',{token:room.access_token,method:'PATCH',data:{version:board.version,categories:board.categories,configuration:invalid}});
  assert.equal(rejectedSave.status,422);
  assert.equal(JSON.parse(h.db.sqlite.prepare('SELECT configuration FROM dorm_configurations WHERE dorm_id=?').get(room.dorm.id).configuration).tasks[1].enabled,false);
  const saved=await h.request('/chores/settings',{token:room.access_token,method:'PATCH',data:{version:board.version,categories:board.categories,configuration:config}});
  assert.equal(saved.status,200,await saved.clone().text());
  const latest=await (await h.request(`/chores/board?invite_code=${room.invite_code}&member_id=${room.member_id}`,{token:room.access_token})).json();
  const named={...config,tasks:[config.tasks[0],{...config.tasks[1],name:'阳台',enabled:true}]};
  const enabled=await h.request('/chores/settings',{token:room.access_token,method:'PATCH',data:{version:latest.version,categories:latest.categories,configuration:named}});
  assert.equal(enabled.status,200,await enabled.clone().text());
  const finalBoard=await (await h.request(`/chores/board?invite_code=${room.invite_code}&member_id=${room.member_id}`,{token:room.access_token})).json();
  assert.equal(finalBoard.categories.find(item=>item.key===key).name,'阳台');
  assert.equal(finalBoard.categories.find(item=>item.key===key).enabled,true);
  const rejected = await create('不可创建',invalid); assert.equal(rejected.status,422);
  assert.equal(JSON.stringify(snapshot()),oldBefore);
  console.log('PASS: disabled unnamed optional task can be created; enabling it requires a name; legacy dorm unchanged');
} finally { h.close(); }
