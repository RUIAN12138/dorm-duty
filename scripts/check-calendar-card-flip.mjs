import assert from 'node:assert/strict';
import {chromium,webkit} from '../frontend/node_modules/@playwright/test/index.mjs';
import {createConversationPreview} from './lib/conversation-preview.mjs';
const safari=process.env.DORM_BROWSER==='webkit';
const preview=await createConversationPreview();
const browser=await (safari?webkit:chromium).launch({headless:true,...(!safari&&process.platform==='darwin'?{executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'}:{})});
let count=0;
const check=(condition,label)=>{assert(condition,label); count++; console.log('PASS',label)};
try {
 const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
 const errors=[]; page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/chores/activity?*',async route=>{const response=await route.fetch();const activity=await response.json();activity.last_completed=activity.last_completed.filter(r=>!['floor','sink'].includes(r.key));activity.last_completed.push({key:'floor',completed_at:'2026-01-01T04:00:00.000Z',assignee_name:'甲'},{key:'sink',completed_at:'2026-01-01T04:00:00.000Z'});await route.fulfill({response,json:activity});});
 await page.goto(preview.url+'/calendar?start=1');
 await page.getByTestId('calendar-view-stats').click();
 const deck=page.locator('.deck-stage'); await deck.waitFor();
 await page.locator('.deck-card.is-front .stat-flip').waitFor();
 await page.waitForTimeout(800);
 const front=()=>page.locator('.deck-card.is-front');
 let button=front().locator('.stat-flip');
 await button.click();
 check(await button.getAttribute('aria-pressed')==='true','tap flips active card');
 await page.waitForTimeout(350);
 check(await front().locator('.stat-back').innerText().then(s=>s.includes('甲')&&s.includes('2026')&&s.includes('12:00')),'back displays the all-history person and full time');
 check((await button.getAttribute('aria-label')).includes('甲')&&(await button.getAttribute('aria-label')).includes('12:00'),'screen reader label includes person and time');
 await button.press('Enter');
 check(await button.getAttribute('aria-pressed')==='false','keyboard flips back');
 const drag=async(dx)=>{const r=await deck.boundingBox();const x=r.x+r.width/2,y=r.y+r.height/2;await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+dx,y,{steps:8});};
 const before=await front().getAttribute('data-card-index');
 await drag(-38);
 const transformDuring=await front().evaluate(e=>getComputedStyle(e).transform);
 await page.mouse.up(); await page.waitForTimeout(90);
 const transformReturn=await front().evaluate(e=>getComputedStyle(e).transform);
 check(transformDuring!==transformReturn,'short drag produces visible recovery');
 await page.waitForTimeout(350);
 check(await front().getAttribute('data-card-index')===before,'short drag stays on same card');
 check(await front().locator('.stat-flip').getAttribute('aria-pressed')==='false','drag does not flip');
 button=front().locator('.stat-flip');await button.click();
 check(await button.getAttribute('aria-pressed')==='true','a click after a short drag still flips');
 await button.click();
 await drag(-160);
 const neighborDuring=await page.locator('.deck-card:not(.is-front)').first().evaluate(e=>getComputedStyle(e).transform);
 await page.mouse.up(); await page.waitForTimeout(350);
 check(await front().getAttribute('data-card-index')!==before,'long drag advances to another card');
 check(neighborDuring!=='none','neighbor has a visible transforming pose');
 button=front().locator('.stat-flip');await button.click();
 check(await front().locator('.stat-back').innerText().then(s=>s.includes('暂无完成记录')),'empty history is explicit');
 await button.click();
 await deck.focus();await deck.press('ArrowRight');await page.waitForTimeout(350);
 button=front().locator('.stat-flip');await button.click();
 check(await front().locator('.stat-back').innerText().then(s=>s.includes('姓名暂不可用')&&s.includes('12:00')),'old API without a name displays an honest fallback');
 await button.click();
 if(!safari){
   const cdp=await page.context().newCDPSession(page),r=await deck.boundingBox();
   const x=r.x+r.width/2,y=r.y+r.height/2,index=await front().getAttribute('data-card-index');
   await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
   await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x-38,y}]});
   await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
   await page.waitForTimeout(350);
   check(await front().getAttribute('data-card-index')===index&&await front().locator('.stat-flip').getAttribute('aria-pressed')==='false','short touch returns without switching or flipping');
   await cdp.detach();
 }
 for(const width of [320,390,430]){await page.setViewportSize({width,height:844});check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`${width}px has no horizontal overflow`)}
 await page.emulateMedia({reducedMotion:'reduce'});
 button=front().locator('.stat-flip'); await button.click();
 check(await button.getAttribute('aria-pressed')==='true','flip works with reduced motion');
 check(await front().locator('.stat-flip-inner').evaluate(e=>getComputedStyle(e).transitionDuration)==='0s','reduced motion skips flip animation');
 check(errors.length===0,'no browser errors');
 console.log(JSON.stringify({engine:safari?'webkit':'chromium',checks:count}));
} finally {await browser.close();await preview.close();}
